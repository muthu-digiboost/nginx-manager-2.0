/**
 * File: manager/src/Nginx/NginxConfigWriter.php
 * Purpose: Generates the nginx files that are DERIVED from settings.json + .env, so they
 *          can never drift from what the UI and the PowerShell scripts believe:
 *            conf/generated/upstreams.conf  one "upstream phpXX" per installed PHP
 *            conf/generated/env.conf        $projects_dir[_x] variables (PROJECTS_DIR*)
 *            conf/manager/manager.conf      the manager UI vhost (127.0.0.1 only)
 * Responsibilities: pure string builders + writeAll() which writes the three files
 * Used by: bin/manager.php config:write (called by start-all.ps1 and install-php.ps1),
 *          PhpController after installing a PHP version
 * Notes: all three files are gitignored (machine-specific). conf/nginx.conf includes
 *        generated/*.conf, manager/*.conf and sites/*.conf in that order.
 */

declare(strict_types=1);

namespace NginxManager\Nginx;

use NginxManager\Support\Env;
use NginxManager\Support\Paths;
use NginxManager\Support\Settings;
use RuntimeException;

final class NginxConfigWriter
{
    private const HEADER = "# GENERATED by manager/bin/manager.php config:write - DO NOT EDIT.\n"
        . "# Source: data/settings.json + .env. Re-run start-all.ps1 (or config:write) to refresh.\n\n";

    public static function upstreams(Settings $settings): string
    {
        $out = self::HEADER;
        foreach ($settings->phpVersions() as $v) {
            $out .= sprintf("# PHP %s (%s)\nupstream %s {\n    server 127.0.0.1:%d;\n}\n\n",
                $v['id'], $v['version'] ?? '?', $v['upstream'], (int) $v['port']);
        }
        return $out;
    }

    /**
     * One nginx variable per project root. $projects_dir always exists (empty when
     * PROJECTS_DIR is not set yet), otherwise nginx refuses to start as soon as one site
     * config references it.
     *
     * @param array<string, string> $roots  varName => folder (Paths::projectRoots())
     */
    public static function envMap(array $roots): string
    {
        $roots += ['projects_dir' => ''];
        ksort($roots);
        $out = self::HEADER;
        foreach ($roots as $var => $path) {
            if (str_contains($path, '"')) {
                throw new RuntimeException("Invalid character in project folder for \$$var");
            }
            $out .= sprintf("map \$host \$%s {\n    default \"%s\";\n}\n\n", $var, $path);
        }
        return $out;
    }

    public static function managerVhost(Settings $settings): string
    {
        $host = Env::get('MANAGER_HOST', '127.0.0.1');
        $port = Env::int('MANAGER_PORT', 8080);
        $php = $settings->phpVersion($settings->managerVersion());
        $upstream = $php['upstream'] ?? 'php83';

        return self::HEADER . <<<CONF
# Nginx Manager UI -> http://{$host}:{$port}
# Runs as Administrator, so it only listens on the loopback address.
server {
    listen       {$host}:{$port};
    server_name  localhost 127.0.0.1;

    root  manager/public;
    index index.php;

    # SAMEORIGIN: other websites cannot frame the manager (clickjacking); its own pages can.
    # Declaring add_header here stops nginx.conf's global CORS headers from being
    # inherited: no other website may read the manager's pages.
    add_header X-Frame-Options "SAMEORIGIN" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header Referrer-Policy "same-origin" always;

    client_max_body_size 64M;

    location / {
        try_files \$uri /index.php\$is_args\$args;
    }

    location ~ \\.php\$ {
        try_files      \$uri =404;
        fastcgi_pass   {$upstream};
        fastcgi_index  index.php;
        fastcgi_param  SCRIPT_FILENAME \$document_root\$fastcgi_script_name;
        include        fastcgi_params;
        fastcgi_read_timeout 300;
    }

    location ~ /\\. {
        deny all;
    }

    error_log   logs/manager-error.log;
    access_log  logs/manager-access.log;
}

CONF;
    }

    /** @return list<string> written files, relative to {base} */
    public static function writeAll(Settings $settings): array
    {
        $files = [
            'conf/generated/upstreams.conf' => self::upstreams($settings),
            'conf/generated/env.conf'       => self::envMap(Paths::projectRoots()),
            'conf/manager/manager.conf'     => self::managerVhost($settings),
        ];
        foreach ($files as $rel => $content) {
            $path = Paths::in($rel);
            if (!is_dir(dirname($path))) {
                mkdir(dirname($path), 0777, true);
            }
            if (file_put_contents($path, $content) === false) {
                throw new RuntimeException("Cannot write $rel");
            }
        }
        return array_keys($files);
    }
}
